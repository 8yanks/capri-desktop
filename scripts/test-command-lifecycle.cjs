const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../src/main/main.js'), 'utf8');
const start = source.indexOf('function sendCommand(');
const end = source.indexOf('// Ctrl+Alt+C:', start);
const calls = [];
const context = vm.createContext({ overlay: null });
vm.runInContext(source.slice(start, end), context);
context.sendCommand('status');
context.overlay = { isDestroyed: () => true };
context.sendCommand('status');
context.overlay = { isDestroyed: () => false, webContents: { isDestroyed: () => true } };
context.sendCommand('status');
context.overlay.webContents = { isDestroyed: () => false, send: (...args) => calls.push(args) };
context.sendCommand('status');
assert.equal(calls.length, 1);
assert.equal(calls[0][0], 'capri:command');
console.log('Missing/destroyed overlay and WebContents guards: PASS');
