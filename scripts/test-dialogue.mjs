import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
let now = 0, callback, clears = 0;
const reducedMotion = { matches: false };
const context = vm.createContext({ reducedMotion, performance: { now: () => now },
  setInterval(fn) { callback = fn; return 1; }, clearInterval() { callback = null; clears++; } });
const source = fs.readFileSync(new URL('../src/renderer/js/dialogue.js', import.meta.url), 'utf8')
  .replace(/^import .*;\r?\n/gm, '').replace('export function', 'function');
vm.runInContext(source + '\nthis.create = dialogueActing;', context);
const acts = [], faces = [];
const capri = { perform: name => acts.push(name), endAct() { this.act = null; }, stance: 'sit' };
const panel = { visible: true, setFace: face => faces.push(face), current: { face: 'wide' } };
const dialogue = context.create(capri, panel);
dialogue.talking(true, panel.current);
assert.equal(acts[0], 'dialogue-curious');
assert.equal(capri.dialogueActive, true);
callback();assert.equal(acts.length,1,'does not spam gestures on every timer tick');
now=3500;callback(); assert.equal(acts.at(-1), 'talk', 'alternates accent and speech beat after a quiet hold');
assert.equal(faces.at(-1), 'look');
dialogue.voice(4); dialogue.talking(false);
assert.equal(capri.dialogueActive, true, 'continues after text reveal while audio plays');
now = 7600; callback();
assert.equal(capri.dialogueActive, false);
dialogue.voice(2);
assert.equal(capri.dialogueActive, true, 'subsequent audio segment resumes acting');
capri.resourceLocked = true; callback();
assert.equal(capri.dialogueActive, false, 'VRAM sleep overrides dialogue');
capri.resourceLocked = false; reducedMotion.matches = true;
dialogue.talking(true, panel.current);
assert.equal(callback, null, 'reduced motion does not schedule repeated gestures');
reducedMotion.matches = false;
panel.current = { face: 'smug' }; dialogue.talking(true, panel.current);
assert.equal(acts.at(-1), 'dialogue-smug');
capri.dragging = true; const count = acts.length; callback();
assert.equal(acts.length, count, 'dragging takes priority');
dialogue.stop(); assert.equal(capri.dialogueActive, false);
assert.ok(clears > 0);
console.log('Dialogue mood, portrait beats, audio duration, segmented speech, resource and motion guards: PASS');
